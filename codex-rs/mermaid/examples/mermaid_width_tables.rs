//! Emit the reference dependency's exact scalar and positive-width ligature tables.
use unicode_width::{UnicodeWidthChar, UnicodeWidthStr};

fn ranges(name: &str, values: Vec<u32>) {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for value in values {
        if let Some(last) = ranges.last_mut() {
            if last.1 + 1 == value {
                last.1 = value;
                continue;
            }
        }
        ranges.push((value, value));
    }
    for (suffix, end) in [("Starts", false), ("Ends", true)] {
        println!("{name}{suffix} :: u32.[");
        for chunk in ranges.chunks(8) {
            print!("    ");
            for &(lo, hi) in chunk {
                print!("0x{:x}, ", if end { hi } else { lo });
            }
            println!();
        }
        println!("]\n");
    }
}

fn lookup(name: &str) {
    println!("\n{name}Has :: (point: u32) -> bool {{");
    println!("    low: s64 = 0; high := {name}Starts.count - 1");
    println!("    while low <= high {{");
    println!("        middle := (low + high) / 2");
    println!("        if point < {name}Starts[middle] {{ high = middle - 1 }}");
    println!("        else if point > {name}Ends[middle] {{ low = middle + 1 }}");
    println!("        else {{ return true }}");
    println!("    }}\n    return false\n}}");
}

fn main() {
    let mut zero = Vec::new();
    let mut wide = Vec::new();
    let mut triple = Vec::new();
    let mut emoji = Vec::new();
    let mut alef = Vec::new();
    let mut lam = Vec::new();
    let mut tifinagh = Vec::new();
    let mut text = String::new();
    for value in 0..=0x10ffff {
        let Some(ch) = char::from_u32(value) else {
            continue;
        };
        let Some(width) = ch.width() else {
            continue;
        };
        match width {
            0 => zero.push(value),
            2 => wide.push(value),
            3 => triple.push(value),
            _ => {}
        }
        if width == 0 {
            continue;
        }
        for (prefix, suffix, expected, output) in [
            ("", "🏻", width + 2, &mut emoji),
            ("ل", "", width + 1, &mut alef),
            ("", "ا", width + 1, &mut lam),
            ("ⴱ⵿", "", width + 2, &mut tifinagh),
        ] {
            text.clear();
            text.push_str(prefix);
            text.push(ch);
            text.push_str(suffix);
            if text.width() != expected {
                output.push(value);
            }
        }
    }
    println!(
        "#scope_module\n// Generated by Xcode's mermaid_width_tables example using unicode-width 0.2.1.\n"
    );
    ranges("Zero", zero);
    ranges("Wide", wide);
    ranges("Triple", triple);
    ranges("EmojiBase", emoji);
    ranges("Alef", alef);
    ranges("Lam", lam);
    ranges("Tifinagh", tifinagh);
    for name in ["Zero", "Wide", "EmojiBase", "Alef", "Lam", "Tifinagh"] {
        lookup(name);
    }
}
